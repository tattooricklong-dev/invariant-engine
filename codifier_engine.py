class FrictionTier(Enum):
    """The three functional tiers of cognitive and technical compilation."""
    ASSIMILATE = "ASSIMILATE"       # Tier 1: 0.0 - 3.0 (Scaffolding & Deconstruction)
    CONSTRUCT = "CONSTRUCT"         # Tier 2: 3.1 - 7.9 (Dependency-Free Standard Library)
    STRESS_TEST = "STRESS_TEST"     # Tier 3: 8.0 - 10.0 (Adversarial Hardening & Shunting)


@dataclass(frozen=True)
class TierRuleSpecification:
    """Structured, typed execution rule contract governing a specific friction tier."""
    tier: str
    action_token: str
    max_memory_mb: float
    timeout_seconds: float
    permitted_modules: List[str]
    enforce_fail_closed: bool
    description: str

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass(frozen=True)
class DirectiveContract:
    """Immutable, strictly typed output vector generated by the Codifier Engine."""
    concept: str
    grip_level: float
    tier: str
    rules: TierRuleSpecification
    concrete_primitive_bindings: List[str]
    backpressure_active: bool
    shunt_telemetry: Dict[str, Any]
    timestamp_utc: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "concept": self.concept,
            "grip_level": self.grip_level,
            "tier": self.tier,
            "rules": self.rules.to_dict(),
            "concrete_primitive_bindings": self.concrete_primitive_bindings,
            "backpressure_active": self.backpressure_active,
            "shunt_telemetry": self.shunt_telemetry,
            "timestamp_utc": self.timestamp_utc,
        }

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, sort_keys=True)

    def validate_schema(self) -> Tuple[bool, List[str]]:
        """
        Validates contract against structural schema invariants.
        Enforces that concrete_primitive_bindings is a strict subset of rules.permitted_modules.
        """
        errors: List[str] = []
        if not self.concept or len(self.concept) > MAX_CONCEPT_LENGTH:
            errors.append(f"concept exceeds length bounds [1, {MAX_CONCEPT_LENGTH}]")
        if not (0.0 <= self.grip_level <= 10.0):
            errors.append("grip_level out of range [0.0, 10.0]")
        if self.tier not in {"ASSIMILATE", "CONSTRUCT", "STRESS_TEST"}:
            errors.append(f"invalid tier identifier: {self.tier}")
        if not isinstance(self.rules, TierRuleSpecification):
            errors.append("rules must be an instance of TierRuleSpecification")
        if not self.concrete_primitive_bindings:
            errors.append("concrete_primitive_bindings cannot be empty")

        # Formal AST Whitelist Invariant: bindings ⊆ permitted_modules
        unpermitted = set(self.concrete_primitive_bindings) - set(self.rules.permitted_modules)
        if unpermitted:
            errors.append(
                f"Concrete bindings violate AST whitelist: {sorted(unpermitted)} not in permitted_modules"
            )

        return len(errors) == 0, errors


