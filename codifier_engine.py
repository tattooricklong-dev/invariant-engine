class CodifierEngine:
    """
    Three-Tier Cognitive Compiler and Engineering Governor.
    Implements strict input bounds, real OS primitives, and typed rule contracts.
    """

    # Keyword mappings for tokenized AST primitive resolution
    KEYWORD_PRIMITIVE_MAP: Dict[frozenset[str], List[str]] = {
        frozenset({"ipc", "pipe", "socket", "stream", "comm", "network"}): [
            "multiprocessing.connection", "socket", "subprocess"
        ],
        frozenset({"file", "disk", "dir", "path", "read", "write", "io"}): [
            "io", "os", "pathlib"
        ],
        frozenset({"sec", "hash", "sha", "perm", "auth", "reg", "gate"}): [
            "hashlib", "winreg" if IS_WIN32 else "os"
        ],
    }

    # Baseline runtime modules always available across all tiers
    BASELINE_RUNTIME: List[str] = ["gc", "sys", "time"]

    def __init__(self, grip_level: float = 5.0, operator_designation: str = "Baremetal Operator"):
        self.designation = "Codifier Engine v5.0 (Triad Certified)"
        self.operator = operator_designation
        self.grip_level = self._validate_and_clamp_grip(grip_level)
        self.substrate = BoundedExecutionSubstrate()

    @staticmethod
    def _validate_and_clamp_grip(val: Any) -> float:
        """Enforces fail-fast boundary validation on grip parameter."""
        try:
            f = float(val)
        except (ValueError, TypeError):
            raise ContractValidationError(
                f"Invalid grip value {val!r}: must be a numeric float between 0.0 and 10.0."
            )
        if f < 0.0 or f > 10.0:
            raise ContractValidationError(
                f"Grip level {f} out of bounds: must be between 0.0 and 10.0 inclusive."
            )
        return f

    def set_grip(self, grip_level: float) -> None:
        """Dynamically adjusts the friction governor between 0.0 and 10.0."""
        self.grip_level = self._validate_and_clamp_grip(grip_level)

    def resolve_tier(self) -> FrictionTier:
        """Categorizes current friction into one of the three foundational thirds."""
        if self.grip_level <= 3.0:
            return FrictionTier.ASSIMILATE
        elif self.grip_level < 8.0:
            return FrictionTier.CONSTRUCT
        else:
            return FrictionTier.STRESS_TEST

    def compile_concept(self, target_concept: str) -> DirectiveContract:
        """
        Executes bounded three-stage validation and synthesis:
          1. Boundary Sanitization (Sanitizes length, strips whitespace, checks null bytes)
          2. Rule Specification Synthesis (Defines permitted AST whitelist)
          3. Substrate Impedance Check & Filtered Primitive Resolution
        """
        if not isinstance(target_concept, str):
            raise ContractValidationError("target_concept must be a valid string")

        sanitized = target_concept.strip()
        if not sanitized:
            raise ContractValidationError("target_concept cannot be empty or pure whitespace")
        if "\0" in sanitized:
            raise ContractValidationError("Null-byte injection detected in target_concept")
        if len(sanitized) > MAX_CONCEPT_LENGTH:
            raise ContractValidationError(
                f"target_concept exceeds maximum permitted length of {MAX_CONCEPT_LENGTH} characters"
            )

        current_tier = self.resolve_tier()
        timestamp = datetime.now(timezone.utc).isoformat()

        # Step 1: Synthesize tier rules first to establish the AST whitelist boundary
        rule_spec = self._synthesize_rule_spec(current_tier)

        # Step 2: Bind primitives strictly constrained by the tier's permitted_modules
        concrete_bindings = self._resolve_primitive_bindings(sanitized, rule_spec.permitted_modules)

        # Step 3: Register active task in volatile queue before impedance check
        self.substrate.enqueue_payload({
            "concept": sanitized,
            "tier": current_tier.value,
            "grip": self.grip_level,
            "timestamp": timestamp,
        })

        # Step 4: Evaluate real OS bus impedance and physical backpressure
        shunt_active, telemetry = self.substrate.evaluate_bus_impedance(self.grip_level)

        contract = DirectiveContract(
            concept=sanitized,
            grip_level=self.grip_level,
            tier=current_tier.value,
            rules=rule_spec,
            concrete_primitive_bindings=concrete_bindings,
            backpressure_active=shunt_active,
            shunt_telemetry=telemetry,
            timestamp_utc=timestamp,
        )

        is_valid, errors = contract.validate_schema()
        if not is_valid:
            raise ContractValidationError(f"Internal Contract Schema Violation: {errors}")

        return contract

    def _resolve_primitive_bindings(self, concept: str, permitted_modules: List[str]) -> List[str]:
        """
        Resolves concrete standard library module names mapped to target concept.
        Enforces AST Whitelist Invariant: resolved bindings are strictly constrained
        to permitted_modules (bindings ⊆ permitted_modules).
        Uses pre-tokenized frozenset matching to eliminate repeated string allocations.
        """
        tokens = frozenset(re.findall(r"\w+", concept.lower()))
        permitted_set = set(permitted_modules)
        candidates: Set[str] = set()

        for keyword_set, modules in self.KEYWORD_PRIMITIVE_MAP.items():
            if not tokens.isdisjoint(keyword_set):
                candidates.update(modules)

        # Always include baseline runtime primitives
        candidates.update(self.BASELINE_RUNTIME)

        # Filter strictly by permitted modules: candidates ∩ permitted_modules
        filtered = candidates.intersection(permitted_set)
        if not filtered:
            # Fallback to runtime baseline present in permitted_modules
            filtered = set(self.BASELINE_RUNTIME).intersection(permitted_set)

        return sorted(filtered)

    def _synthesize_rule_spec(self, tier: FrictionTier) -> TierRuleSpecification:
        """Constructs an immutable, typed rule specification contract with comprehensive module whitelists."""
        if tier == FrictionTier.ASSIMILATE:
            return TierRuleSpecification(
                tier="ASSIMILATE",
                action_token="READ_AND_DECOMPILE",
                max_memory_mb=128.0,
                timeout_seconds=3.0,
                permitted_modules=[
                    "ast", "dis", "gc", "inspect", "io", "json", "os", "pathlib", "sys", "time"
                ],
                enforce_fail_closed=False,
                description="Structural deconstruction: Map data layouts and invariants without writing active code."
            )
        elif tier == FrictionTier.CONSTRUCT:
            return TierRuleSpecification(
                tier="CONSTRUCT",
                action_token="BUILD_THE_TOOL",
                max_memory_mb=256.0,
                timeout_seconds=10.0,
                permitted_modules=[
                    "dataclasses", "gc", "hashlib", "io", "json",
                    "multiprocessing.connection", "os", "pathlib", "socket",
                    "subprocess", "sys", "time", "winreg" if IS_WIN32 else "os"
                ],
                enforce_fail_closed=True,
                description="Synthesis: Construct standalone, dependency-free code using Python standard library only."
            )
        else: # STRESS_TEST
            return TierRuleSpecification(
                tier="STRESS_TEST",
                action_token="TRIAL_BY_FIRE",
                max_memory_mb=512.0,
                timeout_seconds=30.0,
                permitted_modules=[
                    "ctypes" if IS_WIN32 else "os", "dataclasses", "gc", "hashlib", "io", "json",
                    "multiprocessing.connection", "os", "pathlib", "socket",
                    "subprocess", "sys", "time", "winreg" if IS_WIN32 else "os"
                ],
                enforce_fail_closed=True,
                description="Adversarial Audit: Enforce timeout boundaries, memory eviction, and fail-closed quarantines."
            )


