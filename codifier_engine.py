def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="codifier_engine",
        description="Codifier Engine v5.0: Triad-Certified Bare-Metal Three-Tier Architecture Governor."
    )
    parser.add_argument(
        "concept",
        nargs="?",
        default="System Architecture Verification",
        help="Target concept, subsystem, or task to compile (max 1024 chars)."
    )
    parser.add_argument(
        "-g", "--grip",
        default="5.0",
        help="Friction governor level (0.0 to 10.0). Controls operational tier."
    )
    parser.add_argument(
        "-o", "--output",
        choices=["text", "json"],
        default="text",
        help="Output format: formatted text summary or strictly typed JSON contract."
    )
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    # Step 1: Input Validation Gate (Exits with 1 on invalid grip)
    try:
        grip_float = CodifierEngine._validate_and_clamp_grip(args.grip)
    except ContractValidationError as err:
        sys.stderr.write(f"[VALIDATION_ERROR] {err}\n")
        sys.stderr.flush()
        return EXIT_VALIDATION_FAILURE

    # Step 2: Engine Execution Gate (Exits with 1 on validation fault, 2 on unexpected execution error)
    try:
        engine = CodifierEngine(grip_level=grip_float)
        contract = engine.compile_concept(args.concept)
    except ContractValidationError as err:
        sys.stderr.write(f"[VALIDATION_ERROR] {err}\n")
        sys.stderr.flush()
        return EXIT_VALIDATION_FAILURE
    except Exception as err:
        sys.stderr.write(f"[EXECUTION_ERROR] Unexpected failure during compilation: {err}\n")
        sys.stderr.flush()
        return EXIT_EXECUTION_FAILURE

    # Step 3: Format & Flush Output
    if args.output == "json":
        sys.stdout.write(contract.to_json() + "\n")
        sys.stdout.flush()
    else:
        sys.stdout.write("=" * 78 + "\n")
        sys.stdout.write(f"  {engine.designation.upper()} // OPERATOR DIRECTIVE\n")
        sys.stdout.write("=" * 78 + "\n")
        sys.stdout.write(f"Timestamp UTC  : {contract.timestamp_utc}\n")
        sys.stdout.write(f"Target Concept : {contract.concept}\n")
        sys.stdout.write(f"Grip Level     : {contract.grip_level:.1f} / 10.0 -> TIER: {contract.tier}\n")
        sys.stdout.write(f"Action Token   : {contract.rules.action_token}\n")
        sys.stdout.write(f"Permitted Libs : {', '.join(contract.rules.permitted_modules)}\n")
        sys.stdout.write(f"OS Primitives  : {', '.join(contract.concrete_primitive_bindings)}\n")
        sys.stdout.write(f"Backpressure   : {'ACTIVE (Physical Shunt Engaged)' if contract.backpressure_active else 'NOMINAL (Stasis)'}\n")
        sys.stdout.write("-" * 78 + "\n")
        sys.stdout.write(f"[RULE SPECIFICATION]\n  {contract.rules.description}\n")
        sys.stdout.write(f"  Max Memory: {contract.rules.max_memory_mb} MB | Timeout: {contract.rules.timeout_seconds}s | Fail-Closed: {contract.rules.enforce_fail_closed}\n")
        if contract.backpressure_active:
            sys.stdout.write("-" * 78 + "\n")
            sys.stdout.write(f"[SHUNT TELEMETRY]\n  Action: {contract.shunt_telemetry.get('action_taken')}\n")
            mem = contract.shunt_telemetry.get("os_memory", {})
            sys.stdout.write(f"  OS Memory Load: {mem.get('memory_load_percent')}% | Avail Physical: {mem.get('avail_phys_mb')} MB\n")
            sys.stdout.write(f"  Queue Items Evicted: {contract.shunt_telemetry.get('evicted_queue_items')} | GC Objects Freed: {contract.shunt_telemetry.get('gc_objects_collected')}\n")
        sys.stdout.write("=" * 78 + "\n")
        sys.stdout.flush()

    # Step 4: Defensive Resource Exhaustion Exit Gate (Exit Code 3)
    # If the rule mandates fail-closed and memory telemetry is critical or invalid, exit with 3
    if contract.rules.enforce_fail_closed and contract.backpressure_active:
        reasons = contract.shunt_telemetry.get("trigger_reasons", [])
        if any("critical" in r or "degraded" in r or "low" in r for r in reasons):
            sys.stderr.write(
                "[RESOURCE_EXHAUSTION] Hardware memory threshold breached under fail-closed enforcement.\n"
            )
            sys.stderr.flush()
            return EXIT_RESOURCE_EXHAUSTION

    return EXIT_SUCCESS


if __name__ == "__main__":
    sys.exit(main())