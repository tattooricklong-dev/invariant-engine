class BoundedExecutionSubstrate:
    """
    Manages process backpressure, real memory boundaries, and physical buffer eviction.
    Zero simulated physics: queries actual OS paging/physical memory margins.
    Fails closed if telemetry is degraded or unavailable.
    """

    def __init__(self, memory_ceiling_mb: float = 512.0, max_queue_capacity: int = 1000):
        self.memory_ceiling_mb = memory_ceiling_mb
        self.volatile_queue: deque[Dict[str, Any]] = deque(maxlen=max_queue_capacity)
        self.flush_count: int = 0

    def enqueue_payload(self, payload: Dict[str, Any]) -> None:
        """Appends active runtime payload to the volatile queue for bounded buffering."""
        self.volatile_queue.append(payload)

    @staticmethod
    def get_real_memory_telemetry() -> Dict[str, Any]:
        """
        Queries physical OS memory counters directly from the operating system.
        Catches typed OS errors and flags telemetry validity for fail-closed handling.
        """
        if IS_WIN32:
            try:
                stat = MEMORYSTATUSEX()
                stat.dwLength = ctypes.sizeof(MEMORYSTATUSEX)
                if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(stat)):
                    return {
                        "platform": "win32",
                        "telemetry_valid": True,
                        "memory_load_percent": int(stat.dwMemoryLoad),
                        "total_phys_mb": round(stat.ullTotalPhys / (1024 * 1024), 2),
                        "avail_phys_mb": round(stat.ullAvailPhys / (1024 * 1024), 2),
                        "commit_total_mb": round(stat.ullTotalPageFile / (1024 * 1024), 2),
                        "commit_avail_mb": round(stat.ullAvailPageFile / (1024 * 1024), 2),
                    }
            except (OSError, AttributeError, ValueError):
                pass

        # Cross-platform / POSIX fallback using /proc/meminfo
        if os.path.exists("/proc/meminfo"):
            try:
                meminfo: Dict[str, float] = {}
                with open("/proc/meminfo", "r", encoding="utf-8") as fh:
                    for line in fh:
                        parts = line.split(":")
                        if len(parts) == 2:
                            key = parts[0].strip()
                            val = parts[1].split()[0].strip()
                            if val.isdigit():
                                meminfo[key] = float(val) / 1024.0
                total = meminfo.get("MemTotal", 0.0)
                avail = meminfo.get("MemAvailable", meminfo.get("MemFree", 0.0))
                if total > 0.0:
                    used = max(0.0, total - avail)
                    load_pct = int((used / total) * 100)
                    return {
                        "platform": "posix",
                        "telemetry_valid": True,
                        "memory_load_percent": load_pct,
                        "total_phys_mb": round(total, 2),
                        "avail_phys_mb": round(avail, 2),
                        "commit_total_mb": round(total, 2),
                        "commit_avail_mb": round(avail, 2),
                    }
            except (OSError, ValueError):
                pass

        # Fail-closed telemetry fallback: marked as invalid
        return {
            "platform": sys.platform,
            "telemetry_valid": False,
            "memory_load_percent": 100,
            "total_phys_mb": 0.0,
            "avail_phys_mb": 0.0,
            "commit_total_mb": 0.0,
            "commit_avail_mb": 0.0,
        }

    def evaluate_bus_impedance(self, grip_level: float) -> Tuple[bool, Dict[str, Any]]:
        """
        Evaluates runtime bus impedance using REAL OS hardware metrics.
        Fails closed (engages backpressure) if OS memory telemetry fails.
        """
        os_mem = self.get_real_memory_telemetry()
        timestamp = datetime.now(timezone.utc).isoformat()

        # Telemetry degraded check (Fail-Closed)
        telemetry_failed = not os_mem.get("telemetry_valid", False) or os_mem.get("avail_phys_mb", 0.0) <= 0.0

        # Physical backpressure criteria:
        # 1. Telemetry failure (Fail-Closed), OR
        # 2. High grip setting (>= 8.0), OR
        # 3. Real OS memory load exceeds 85%, OR
        # 4. Available physical memory drops below 256 MB
        crit_mem_load = os_mem.get("memory_load_percent", 0) >= 85
        low_avail_mem = 0.0 < os_mem.get("avail_phys_mb", 0.0) < 256.0
        grip_forced = grip_level >= 8.0

        backpressure_triggered = telemetry_failed or crit_mem_load or low_avail_mem or grip_forced

        telemetry: Dict[str, Any] = {
            "timestamp_utc": timestamp,
            "grip_level": grip_level,
            "os_memory": os_mem,
            "backpressure_active": backpressure_triggered,
            "trigger_reasons": [],
            "action_taken": "NOMINAL_STASIS",
            "evicted_queue_items": 0,
            "gc_objects_collected": 0,
        }

        if telemetry_failed:
            telemetry["trigger_reasons"].append("OS memory telemetry degraded/unavailable - failing closed")
        if crit_mem_load:
            telemetry["trigger_reasons"].append(f"OS memory load critical ({os_mem['memory_load_percent']}%)")
        if low_avail_mem:
            telemetry["trigger_reasons"].append(f"Available physical memory low ({os_mem['avail_phys_mb']} MB)")
        if grip_forced:
            telemetry["trigger_reasons"].append(f"Adversarial grip friction threshold active ({grip_level:.1f} >= 8.0)")

        if backpressure_triggered:
            action, evicted, gc_count = self._execute_physical_shunt()
            telemetry["action_taken"] = action
            telemetry["evicted_queue_items"] = evicted
            telemetry["gc_objects_collected"] = gc_count

        return backpressure_triggered, telemetry

    def _execute_physical_shunt(self) -> Tuple[str, int, int]:
        """
        Physical OS Eviction: Drains the real in-memory queue, forces an actual
        gc.collect() cycle, and logs concrete telemetry metrics.
        """
        self.flush_count += 1
        evicted_count = len(self.volatile_queue)
        self.volatile_queue.clear()

        # Real physical Python GC sweep
        collected_objects = gc.collect()

        action_msg = (
            f"PHYSICAL_BACKPRESSURE_SHUNT_EXECUTED: Evicted {evicted_count} queue items; "
            f"gc.collect() freed {collected_objects} unreachable objects [Cycle #{self.flush_count}]."
        )
        return action_msg, evicted_count, collected_objects


